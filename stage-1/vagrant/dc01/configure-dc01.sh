#!/usr/bin/env bash
# ==============================================================================
# Enterprise Cloud Migration Lab — Phase 6: Samba Active Directory & DNS Setup
# Target Machine: DC01 (192.168.10.10)
#
# What this script executes end-to-end on DC01:
#   1. Sets hostname to DC01.corp.streamflix.lab
#   2. Disables systemd-resolved DNS stub listener (frees port 53 for Samba DNS)
#   3. Installs Samba, Kerberos, Winbind, and LDAP utilities non-interactively
#   4. Provisions Samba Active Directory Domain Controller with integrated DNS
#   5. Configures Kerberos krb5.conf and local DNS resolver
#   6. Enables & starts samba-ad-dc service
#   7. Creates test domain users and service accounts
#   8. Executes automated DNS, LDAP, and Kerberos health checks
# ==============================================================================

set -euo pipefail

DOMAIN_REALM="CORP.STREAMFLIX.LAB"
DOMAIN_NETBIOS="STREAMFLIX"
DOMAIN_PASS="LabAdmin2026!#"
DNS_FORWARDER="1.1.1.1"

echo "=================================================================="
echo "  Enterprise Cloud Migration Lab: DC01 Samba AD DS & DNS Setup     "
echo "=================================================================="

# 1. Root check
if [[ $EUID -ne 0 ]]; then
   echo "[-] This script must be run as root (e.g. sudo bash configure-dc01.sh)"
   exit 1
fi

echo -e "\n>>> [1/7] Configuring Hostname and /etc/hosts..."
hostnamectl set-hostname DC01.corp.streamflix.lab
sed -i '/127.0.1.1/d' /etc/hosts
if ! grep -q "192.168.10.10 DC01.corp.streamflix.lab DC01" /etc/hosts; then
    echo "192.168.10.10 DC01.corp.streamflix.lab DC01" >> /etc/hosts
fi
echo "[OK] Hostname configured: $(hostname -f)"

echo -e "\n>>> [2/7] Disabling systemd-resolved port 53 listener..."
# systemd-resolved listens on 127.0.0.53:53 by default, which conflicts with Samba internal DNS
if [[ -f /etc/systemd/resolved.conf ]]; then
    sed -i 's/^#DNSStubListener=yes/DNSStubListener=no/' /etc/systemd/resolved.conf
    sed -i 's/^DNSStubListener=yes/DNSStubListener=no/' /etc/systemd/resolved.conf
    if ! grep -q "DNSStubListener=no" /etc/systemd/resolved.conf; then
        echo "DNSStubListener=no" >> /etc/systemd/resolved.conf
    fi
fi
systemctl restart systemd-resolved || true

echo -e "\n>>> [3/7] Installing Samba AD DS and Kerberos packages..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq \
    samba \
    smbclient \
    krb5-user \
    winbind \
    libpam-winbind \
    libnss-winbind \
    libpam-krb5 \
    dnsutils \
    ldap-utils

echo "[OK] Required packages installed."

echo -e "\n>>> [4/7] Provisioning Samba Active Directory Domain..."
# Stop and mask standard services (Samba AD uses samba-ad-dc daemon instead)
systemctl stop smbd nmbd winbind || true
systemctl mask smbd nmbd winbind || true

# Backup default smb.conf
if [[ -f /etc/samba/smb.conf ]]; then
    mv /etc/samba/smb.conf "/etc/samba/smb.conf.orig-$(date +%s)"
fi

# Provision the domain
samba-tool domain provision \
    --use-rfc2307 \
    --realm="${DOMAIN_REALM}" \
    --domain="${DOMAIN_NETBIOS}" \
    --server-role=dc \
    --dns-backend=SAMBA_INTERNAL \
    --dns-forwarder="${DNS_FORWARDER}" \
    --adminpass="${DOMAIN_PASS}"

echo "[OK] Samba AD Domain provisioned successfully."

echo -e "\n>>> [5/7] Configuring Kerberos and DNS Resolution..."
# Set up Kerberos configuration generated by Samba
if [[ -f /var/lib/samba/private/krb5.conf ]]; then
    cp /var/lib/samba/private/krb5.conf /etc/krb5.conf
fi

# Configure static DNS resolver pointing to DC01 itself
rm -f /etc/resolv.conf
cat <<EOF > /etc/resolv.conf
nameserver 127.0.0.1
search corp.streamflix.lab
EOF

echo -e "\n>>> [6/7] Starting samba-ad-dc Service..."
systemctl unmask samba-ad-dc || true
systemctl enable --now samba-ad-dc
sleep 5

echo -e "\n>>> [7/7] Creating Test Domain Accounts & Service Accounts..."
# Create test domain user for StreamFlix media lab
samba-tool user create streaminguser "StreamFlix2026!#" \
    --userou="CN=Users" \
    --description="StreamFlix Test User" || true

# Create application service account
samba-tool user create svc-streamflix "ServiceFlix2026!#" \
    --userou="CN=Users" \
    --description="StreamFlix Backend Service Account" || true

echo -e "\n=================================================================="
echo "  Validation & Health Check Summary                               "
echo "=================================================================="

echo -e "\n--- Domain Info ---"
samba-tool domain info 127.0.0.1

echo -e "\n--- Kerberos Authentication Test ---"
echo "${DOMAIN_PASS}" | kinit administrator@${DOMAIN_REALM}
klist

echo -e "\n--- DNS SRV Record Resolution ---"
host -t SRV _ldap._tcp.${DOMAIN_REALM,,} 127.0.0.1 || true
host -t SRV _kerberos._udp.${DOMAIN_REALM,,} 127.0.0.1 || true

echo -e "\n--- SMB Shares Check ---"
smbclient -L localhost -U%

echo -e "\n[SUCCESS] DC01 Active Directory Domain Controller (${DOMAIN_REALM}) is online and healthy!"
